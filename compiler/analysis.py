def extract_data_value(blocks):
    data_values = {}
    data_block = {}
    for label, block in blocks.items():
        for st in block.body:
            if isinstance(st, ir.Assign):
                data_values[st.target.name] = st.value
                data_block[st.target.name] = label
    return data_values, data_block


def extract_latest_write_accesses_in_loop(lp_header, writes, loop_bodies):
    access_statement_map = {}
    latest_accesses = {}
    for h in loop_bodies[lp_header]:
        sts = writes[h].keys()
        sts = sorted(sts)
        for s in sts:
            access_statement_map[writes[h][s]] = (h, s)
    for a, a_info in access_statement_map.items():
        h = a_info[0]
        s = a_info[1]
        if h not in latest_accesses:
            latest_accesses[h] = {}
        latest_accesses[h][s] = a
    return latest_accesses


