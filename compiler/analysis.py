def extract_iter_variables(blocks, loop_bodies, lp_pars):
    iter_vars_list = {}
    iter_vars = {}
    loop_iter_bodies = {}
    for lp, body in loop_bodies.items():
        loop_iter_bodies[lp] = min(body)
    for lp, body_label in loop_iter_bodies.items():
        iter_vars_list[lp] = []
        st = blocks[body_label].body[0]
        iter_vars[lp] = st.target
    return iter_vars


def find_all_loop_bodies(cfg):
    loop_bodies = {}
