def find_loop_structure(cfg, loop, covered_loops, lp_pars):
    in_loops = cfg.in_loops(loop)
    if len(in_loops) == 1:
        pass
    else:
        for il in in_loops:
            il_header = il.header
            if il_header != loop:
                find_loop_structure(cfg, il_header, covered_loops, lp_pars)
        for il in in_loops:
            il_header = il.header
            if il_header != loop:
                if il_header not in covered_loops:
                    lp_pars[loop] = il_header
                    covered_loops.add(il_header)


def create_spf_tree(lp_pars, loop_bodies):
    spf_tree = {-1: []}
    for lp in loop_bodies.keys():
        spf_tree[lp] = []
        if lp not in lp_pars:
            spf_tree[-1].append(lp)
    for lp, par in lp_pars.items():
        spf_tree[par].append(lp)
    for lp, bodies in loop_bodies.items():
        spf_tree[lp] += bodies
    for lp in spf_tree:
        spf_tree[lp] = sorted(spf_tree[lp])
    return spf_tree


