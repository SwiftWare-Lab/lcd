def create_statement_schedule(stmnt_labels, spf_tree, iter_vars):
    print(spf_tree)
    schedule = {}
    stack = [(-1, 0, 0)]
    schedule_queue = []
    while len(stack) > 0:
        lp, s_counter, cur_level = stack.pop()
        assert lp in iter_vars or lp == -1, "Loop Header Conflict"
        if lp in iter_vars:
            schedule_queue = schedule_queue[:cur_level * 2 - 2]
            schedule_queue.append(str(s_counter))
            s_counter = 0
            schedule_queue.append(iter_vars[lp].name)
            schedule[lp] = {}
        for ilp in spf_tree[lp]:
            if ilp not in stmnt_labels:
                assert ilp in stmnt_labels[lp], "Loop Body Conflict"
                for st in stmnt_labels[lp][ilp]:
                    schedule_queue.append(str(s_counter))
                    schedule[lp][st] = Schedule(deepcopy(schedule_queue))
                    schedule_queue.pop()
                    s_counter += 1
            else:
                level = cur_level + 1
                stack.append((ilp, s_counter, level))
                s_counter += 1
    return schedule


