def extract_loop_header_body_map(loop_bodies, lp_pars):
    header_bodies = {}
    for lp, par in lp_pars.items():
        header_bodies[par] = []
        for body in loop_bodies[par]:
            if body not in loop_bodies[lp]:
                header_bodies[par].append(body)
    for lp, par in lp_pars.items():
        if lp not in header_bodies:
            header_bodies[lp] = deepcopy(loop_bodies[lp])
    return header_bodies


def symbolize_set_item_lhs(statement, data_values):
    # Symbolizing data space
    if not statement.target.name.startswith("$"):
        arr = statement.target.name
    else:
        # Works when we have multidimensional array
        arr_p = []
        translate_read_access_expressions(data_values, statement.target, arr_p)
        if len(arr_p) > 0:
            arr = arr_p[0]
    # symbolizing index
    if not statement.index.name.startswith("$"):
        return Access(arr, statement.index.name)
    else:
        index_syms = []
        symbolize_index(data_values, statement.index, index_syms)
        return Access(arr, ' '.join(list(map(str, index_syms))))


def extract_read_accesses_from_rhs(statement, data_values):
    read_statements = []
    read_accesses = []
    translate_read_access_expressions(data_values, statement.value, read_statements)
    for r in read_statements:
        if isinstance(r, Access):
            read_accesses.append(r)
        elif isinstance(r, ir.Var):
            read_accesses.append(Access(r.name, None))
    return read_accesses


# This function iterates data_value recursively and recreates symbolic representation of the access expressions.
# output is stored in the reads list.(last arg)
def translate_read_access_expressions(data_value, var, reads):
    if isinstance(var, ir.Expr) and var.op == 'getitem':
        reads.append(convert_get_item_to_access(var, data_value))
    elif isinstance(var, ir.Expr) and (var.op == 'binop' or var.op == 'inplace_binop'):
        translate_read_access_expressions(data_value, var.lhs, reads)
        translate_read_access_expressions(data_value, var.rhs, reads)
    elif isinstance(var, ir.Assign):
        translate_read_access_expressions(data_value, var.value, reads)
    elif isinstance(var, ir.Var):
        if not var.name.startswith('$'):
            reads.append(var)
        elif var.name in data_value:
            translate_read_access_expressions(data_value, data_value[var.name], reads)


def convert_get_item_to_access(statement, data_values):
    if not statement.value.name.startswith("$"):
        arr = statement.value.name
    else:
        # Works when we have multidimensional array
        arr_p = []
        translate_read_access_expressions(data_values, statement.value, arr_p)
        arr = arr_p[0]
    # arr = statement.value
    untranslated_index = statement.index
    vars = []
    symbolize_index(data_values, untranslated_index, vars)
    if len(vars) == 1:  # TODO: For now I assume that accesses are either access arrays or affine functions of loop bounds
        ind_var = vars[0]
        return Access(arr, ind_var)
    elif len(vars) > 1:
        return Access(arr, Expression(vars))


def symbolize_index(data_value, var, symbols_list):
    # print(data_value)
    if isinstance(var, ir.Expr) and var.op == 'getitem':
        symbols_list.append(convert_get_item_to_access(var, data_value))
    elif isinstance(var, ir.Expr) and (var.op == 'binop' or var.op == 'inplace_binop'):
        symbolize_index(data_value, var.lhs, symbols_list)
        symbols_list.append(symbolize_operator(var.fn))
        symbolize_index(data_value, var.rhs, symbols_list)
    elif isinstance(var, ir.Assign):
        symbolize_index(data_value, var.value, symbols_list)
    elif isinstance(var, ir.Var):
        if not var.name.startswith('$'):
            symbols_list.append(var.name)
        elif var.name in data_value:
            symbolize_index(data_value, data_value[var.name], symbols_list)
    elif isinstance(var, ir.Const):
        symbols_list.append(var.value)


def symbolize_operator(fn):
    operator_to_string = {
        operator.add: '+',
        operator.sub: '-',
        operator.mul: '*',
        operator.truediv: '/',
        operator.floordiv: '//',
        operator.mod: '%',
        operator.pow: '**',
        operator.and_: '&',
        operator.or_: '|',
        operator.xor: '^',
        operator.eq: '==',
        operator.ne: '!=',
        operator.lt: '<',
        operator.le: '<=',
        operator.gt: '>',
        operator.ge: '>='
    }
    return operator_to_string[fn]



