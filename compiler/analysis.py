def extract_read_write_accesses(blocks,data_values, loop_bodies, lp_pars):
    reads = {}
    writes = {}
    accesses = {'reads': reads, 'writes': writes}
    stmnts_label = {}
    s_counter = 0
    loop_header_bodies = extract_loop_header_body_map(loop_bodies, lp_pars)
    for label, block in loop_header_bodies.items():
        reads[label] = {}
        writes[label] = {}
        stmnts = blocks[block].body
        stmnts_label[label] = {}
        for s, st in enumerate(stmnts):
            if isinstance(st, ir.SetItem):
                writes[label][s] = symbolize_set_item_lhs(st, data_values)
                reads[label][s] = extract_read_accesses_from_rhs(st, data_values)
            # Any extra variable generated by numba starts with '$'.
            elif isinstance(st, ir.Assign) and not st.target.name.startswith('$'):
                writes[label][s] = Access(st.target.name, None)
                reads[label][s] = extract_read_accesses_from_rhs(st, data_values)
            else:
                continue
            s_counter += 1
            stmnts_label[label][s] = 'S{}'.format(s_counter)
    return accesses, stmnts_label

def extract_loop_header_body_map(loop_bodies, lp_pars):
    header_bodies = {}
    for lp, par in lp_pars.items():
        for body in loop_bodies[par]:
            if body not in loop_bodies[lp]:
                header_bodies[par] = body
        if lp not in header_bodies:
            header_bodies[lp] = loop_bodies[lp][0]
    return header_bodies

def symbolize_set_item_lhs(statement, data_values):
    # Symbolizing data space
    if not statement.target.name.startswith("$"):
        arr = statement.target.name
    else:
        # Works when we have multidimensional array
        arr_p = []
        translate_read_access_expressions(data_values, statement.target, arr_p)
        if len(arr_p) > 0:
            arr = arr_p[0]
    # symbolizing index
    if not statement.index.name.startswith("$"):
        return Access(arr, statement.index.name)
    else:
        index_syms = []
        symbolize_index(data_values, statement.index, index_syms)
        return Access(arr, ' '.join(list(map(str, index_syms))))

def extract_read_accesses_from_rhs(statement, data_values):
    read_statements = []
    read_accesses = []
    translate_read_access_expressions(data_values, statement.value, read_statements)
    for r in read_statements:
        if isinstance(r, Access):
            read_accesses.append(r)
        elif isinstance(r, ir.Var):
            read_accesses.append(Access(r.name, None))
    return read_accesses


# This function iterates data_value recursively and recreates symbolic representation of the access expressions.
# output is stored in the reads list.(last arg)
def translate_read_access_expressions(data_value, var, reads):

    if isinstance(var, ir.Expr) and var.op == 'getitem':
        reads.append(convert_get_item_to_access(var, data_value))
    elif isinstance(var, ir.Expr) and (var.op == 'binop' or var.op == 'inplace_binop'):
        translate_read_access_expressions(data_value, var.lhs, reads)
        translate_read_access_expressions(data_value, var.rhs, reads)
    elif isinstance(var, ir.Assign):
        translate_read_access_expressions(data_value, var.value, reads)
    elif isinstance(var, ir.Var):
        if not var.name.startswith('$'):
            reads.append(var)
        elif var.name in data_value:
            translate_read_access_expressions(data_value, data_value[var.name], reads)

def convert_get_item_to_access(statement, data_values):
    if not statement.value.name.startswith("$"):
        arr = statement.value.name
    else:
        # Works when we have multidimensional array
        arr_p = []
        translate_read_access_expressions(data_values, statement.value, arr_p)
        arr = arr_p[0]
    # arr = statement.value
    untranslated_index = statement.index
    vars = []
    symbolize_index(data_values, untranslated_index, vars)
    if len(vars) == 1:  # TODO: For now I assume that accesses are either access arrays or affine functions of loop bounds
        ind_var = vars[0]
        return Access(arr, ind_var)
    elif len(vars) > 1:
        return Access(arr, Expression(vars))

def symbolize_index(data_value, var, symbols_list):
    # print(data_value)
    if isinstance(var, ir.Expr) and var.op == 'getitem':
        symbols_list.append(convert_get_item_to_access(var, data_value))
    elif isinstance(var, ir.Expr) and (var.op == 'binop' or var.op == 'inplace_binop'):
        symbolize_index(data_value, var.lhs, symbols_list)
        symbols_list.append(symbolize_operator(var.fn))
        symbolize_index(data_value, var.rhs, symbols_list)
    elif isinstance(var, ir.Assign):
        symbolize_index(data_value, var.value, symbols_list)
    elif isinstance(var, ir.Var):
        if not var.name.startswith('$'):
            symbols_list.append(var.name)
        elif var.name in data_value:
            symbolize_index(data_value, data_value[var.name], symbols_list)
    elif isinstance(var, ir.Const):
        symbols_list.append(var.value)

def symbolize_operator(fn):
    operator_to_string = {
        operator.add: '+',
        operator.sub: '-',
        operator.mul: '*',
        operator.truediv: '/',
        operator.floordiv: '//',
        operator.mod: '%',
        operator.pow: '**',
        operator.and_: '&',
        operator.or_: '|',
        operator.xor: '^',
        operator.eq: '==',
        operator.ne: '!=',
        operator.lt: '<',
        operator.le: '<=',
        operator.gt: '>',
        operator.ge: '>='
    }
    return operator_to_string[fn]

def create_statement_schedule(blocks, cfg, stmnt_labels, loop_bodies, lp_pars):
    spf_tree = create_spf_tree(lp_pars, loop_bodies.keys())
    iter_vars = extract_iter_variables(blocks, loop_bodies, lp_pars)
    schedule = {}
    iter_set = []
    for i, lp in enumerate(spf_tree[-1]):
        iter_set.append(str(i))
        extract_statement_schedules(stmnt_labels, spf_tree, iter_vars, iter_set, lp, schedule)
        iter_set.pop()
    return schedule

def extract_statement_schedules(statements, spf_tree, iter_vars, iter_set, loop, schedule):
    iter_set.append(iter_vars[loop].name)
    schedule[loop] = {}
    for i, lp in enumerate(spf_tree[loop]):
        iter_set.append(str(i))
        extract_statement_schedules(statements, spf_tree, iter_vars, iter_set, lp, schedule)
        iter_set.pop()
    ordered_sts = sorted(statements[loop].keys())
    for i, st in enumerate(ordered_sts):
        iter_set.append(str(i))
        iter_set_copy = deepcopy(iter_set)
        schedule[loop][st] = Schedule(iter_set_copy)
        iter_set.pop()
    iter_set.pop()

def extract_iter_variables(blocks, loop_bodies, lp_pars):
    iter_vars_list = {}
    iter_vars = {}
    for lp, body_labels in loop_bodies.items():
        iter_vars_list[lp] = []
        for b_label in body_labels:
            st = blocks[b_label].body[0]
            iter_vars_list[lp].append(st.target)
    for lp, lp_par in lp_pars.items():
        for var in iter_vars_list[lp]:
            iter_vars_list[lp_par].remove(var)
    for lp, iters in iter_vars_list.items():
        iter_vars[lp] = iters[0]
    return iter_vars


def find_all_loop_bodies(cfg):
    loop_bodies = {}
    # print(cfg.loops())
    loops = cfg.loops()
    print(loops)
    lp_exits = set()
    lp_pars = {}
    for lp in loops:
        lp_exits.add(loops[lp].exits.pop())
    for lp in loops:
        loop_bodies[lp] = []
        if lp not in lp_pars:
            covered_loops = set()
            find_loop_structure(cfg, lp, covered_loops, lp_pars)
        loop = loops[lp]
        for x in loop.body:
            if x not in loops and x not in lp_exits:
                loop_bodies[lp].append(x)
    return loop_bodies, lp_pars


def find_loop_structure(cfg, loop, covered_loops, lp_pars):
    in_loops = cfg.in_loops(loop)
    if len(in_loops) == 1:
        pass
    else:
        for il in in_loops:
            il_header = il.header
            if il_header != loop:
                find_loop_structure(cfg, il_header, covered_loops, lp_pars)
        for il in in_loops:
            il_header = il.header
            if il_header != loop:
                if il_header not in covered_loops:
                    lp_pars[loop] = il_header
                    covered_loops.add(il_header)

def create_spf_tree(lp_pars, lp_headers):
    spf_tree = {-1: []}
    for lp in lp_headers:
        spf_tree[lp] = []
        if lp not in lp_pars:
            spf_tree[-1].append(lp)
    for lp, par in lp_pars.items():
        spf_tree[par].append(lp)
    for lp in spf_tree:
        spf_tree[lp] = sorted(spf_tree[lp])
    return spf_tree



